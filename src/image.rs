/// Minimal valid GIF89a - 1x1 pixel blue.
const GIF_1X1: &[u8] = &[
    // Header
    0x47, 0x49, 0x46, 0x38, 0x39, 0x61, // "GIF89a"
    // Logical screen descriptor
    0x01, 0x00, // width = 1
    0x01, 0x00, // height = 1
    0x80, // GCT flag, 1 bit colour resolution, no sort, GCT size = 2
    0x00, // background colour index
    0x00, // pixel aspect ratio
    // Global colour table (2 entries: blue, black)
    0x00, 0x00, 0xFF, // colour 0: blue
    0x00, 0x00, 0x00, // colour 1: black
    // Image descriptor
    0x2C, // image separator
    0x00, 0x00, // left
    0x00, 0x00, // top
    0x01, 0x00, // width = 1
    0x01, 0x00, // height = 1
    0x00, // no local colour table
    // Image data
    0x02, // LZW minimum code size
    0x02, // block size = 2
    0x44, 0x01, // compressed data
    0x00, // block terminator
    // Trailer
    0x3B,
];

// ── Handlers ────────────────────────────────────────────────────────

async fn png_handler() -> Response {
    (
        StatusCode::OK,
        [(header::CONTENT_TYPE, HeaderValue::from_static("image/png"))],
        PNG_8X8,
    )
        .into_response()
}

async fn jpeg_handler() -> Response {
    (
        StatusCode::OK,
        [(header::CONTENT_TYPE, HeaderValue::from_static("image/jpeg"))],
        JPEG_1X1,
    )
        .into_response()
}

async fn gif_handler() -> Response {
    (
        StatusCode::OK,
        [(header::CONTENT_TYPE, HeaderValue::from_static("image/gif"))],
        GIF_1X1,
    )
        .into_response()
}

// ── Router ──────────────────────────────────────────────────────────

pub fn router(_state: &AppState) -> Router<AppState> {
    Router::new()
        .route("/image/png", get(png_handler))
        .route("/image/jpeg", get(jpeg_handler))
        .route("/image/gif", get(gif_handler))
}

pub fn catalog() -> Vec<Endpoint> {
    vec![
        Endpoint::new("/image/png", &["GET"], category::INFO, "Minimal PNG image")
            .example(Example::get("PNG image", "/image/png")),
        Endpoint::new(
            "/image/jpeg",
            &["GET"],
            category::INFO,
            "Minimal JPEG image",
        )
        .example(Example::get("JPEG image", "/image/jpeg")),
        Endpoint::new("/image/gif", &["GET"], category::INFO, "Minimal GIF image")
            .example(Example::get("GIF image", "/image/gif")),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::body::Body;
    use axum::http::Request;
    use tower::ServiceExt;

    fn test_app() -> Router {
        crate::test_support::module_app(router)
    }

    fn get_req(uri: &str) -> Request<Body> {
        Request::builder()
            .uri(uri)
            .body(Body::empty())
            .expect("request")
    }

    #[tokio::test]
    async fn png_returns_valid_content_type() {
        let app = test_app();
        let resp = app.oneshot(get_req("/image/png")).await.expect("response");
        assert_eq!(resp.status(), StatusCode::OK);
        assert_eq!(
            resp.headers()
                .get("content-type")
                .expect("ct")
                .to_str()
                .expect("str"),
            "image/png"
        );
        let body = axum::body::to_bytes(resp.into_body(), usize::MAX)
            .await
            .expect("body");
        assert!(!body.is_empty());
        // Check PNG signature
        assert_eq!(&body[..4], &[0x89, 0x50, 0x4E, 0x47]);
    }

    #[tokio::test]
    async fn jpeg_returns_valid_content_type() {
        let app = test_app();
        let resp = app.oneshot(get_req("/image/jpeg")).await.expect("response");
        assert_eq!(resp.status(), StatusCode::OK);
        assert_eq!(
            resp.headers()
                .get("content-type")
                .expect("ct")
                .to_str()
                .expect("str"),
            "image/jpeg"
        );
        let body = axum::body::to_bytes(resp.into_body(), usize::MAX)
            .await
            .expect("body");
        // Check JPEG SOI marker
        assert_eq!(&body[..2], &[0xFF, 0xD8]);
    }

    #[tokio::test]
    async fn gif_returns_valid_content_type() {
        let app = test_app();
        let resp = app.oneshot(get_req("/image/gif")).await.expect("response");
        assert_eq!(resp.status(), StatusCode::OK);
        assert_eq!(
            resp.headers()
                .get("content-type")
                .expect("ct")
                .to_str()
                .expect("str"),
            "image/gif"
        );
        let body = axum::body::to_bytes(resp.into_body(), usize::MAX)
            .await
            .expect("body");
        // Check GIF header
        assert_eq!(&body[..6], b"GIF89a");
    }
}
