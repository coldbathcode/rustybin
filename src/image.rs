/// Minimal 8x8 red PNG (RGBA).
/// Generated structure: PNG signature + IHDR + IDAT (zlib-compressed) + IEND
const PNG_8X8: &[u8] = &[
    // PNG signature
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // IHDR chunk (13 bytes data)
    0x00, 0x00, 0x00, 0x0D, // length = 13
    0x49, 0x48, 0x44, 0x52, // "IHDR"
    0x00, 0x00, 0x00, 0x08, // width = 8
    0x00, 0x00, 0x00, 0x08, // height = 8
    0x02, // bit depth = 8, colour type = 2 (RGB)
    0x00, 0x00, 0x00, // compression, filter, interlace
    0x4B, 0x6D, 0x12, 0x56, // CRC
    // IDAT chunk (zlib compressed pixel data)
    0x00, 0x00, 0x00, 0x1D, // length = 29
    0x49, 0x44, 0x41, 0x54, // "IDAT"
    // zlib data: 8 rows of (filter_byte=0 + 8 pixels of RGB(255,0,0))
    0x78, 0x01, 0x62, 0xF8, 0xCF, 0xC0, 0x00, 0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x05, 0x18, 0xD8,
    0x4E, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xC0, 0x59, 0xD5,
    0x71, // CRC (placeholder)
    // IEND chunk
    0x00, 0x00, 0x00, 0x00, // length = 0
    0x49, 0x45, 0x4E, 0x44, // "IEND"
    0xAE, 0x42, 0x60, 0x82, // CRC
];

